echo "WINDOW_MIN_WEIGHT=${WINDOW_MIN_WEIGHT} ADAPT_MIN_FACTOR=${ADAPT_MIN_FACTOR} ADAPT_MAX_FACTOR=${ADAPT_MAX_FACTOR}"
echo "STATIC_MASK_WARMUP_EPOCHS=${STATIC_MASK_WARMUP_EPOCHS} STATIC_MASK_MAX_BATCHES=${STATIC_MASK_MAX_BATCHES}"
echo "TEMPORAL_MASK_RELIABILITY_GATE=${TEMPORAL_MASK_RELIABILITY_GATE}"
echo "TEMPORAL_MASK_RELIABILITY_LOW=${TEMPORAL_MASK_RELIABILITY_LOW} TEMPORAL_MASK_RELIABILITY_HIGH=${TEMPORAL_MASK_RELIABILITY_HIGH}"
echo "TEMPORAL_SUPPORT_SMOOTH_KERNEL=${TEMPORAL_SUPPORT_SMOOTH_KERNEL}"
echo "REMOTE_PARTITION_MODE=${REMOTE_PARTITION_MODE} REMOTE_PHASE_COUNT=${REMOTE_PHASE_COUNT}"
echo "HAR_PARTITION_MODE=${HAR_PARTITION_MODE} HAR_PHASE_COUNT=${HAR_PHASE_COUNT}"

exec bash "${SCRIPT_DIR}/run_v262a_soft_window_probe.sh"
