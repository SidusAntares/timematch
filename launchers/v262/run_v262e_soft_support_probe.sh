export WINDOW_MIN_WEIGHT="${WINDOW_MIN_WEIGHT:-0.20}"
export STATIC_MASK_WARMUP_EPOCHS="${STATIC_MASK_WARMUP_EPOCHS:-3}"
export STATIC_MASK_MAX_BATCHES="${STATIC_MASK_MAX_BATCHES:-64}"
export TEMPORAL_MASK_RELIABILITY_GATE="${TEMPORAL_MASK_RELIABILITY_GATE:-true}"
export TEMPORAL_MASK_RELIABILITY_LOW="${TEMPORAL_MASK_RELIABILITY_LOW:-0.0005}"
export TEMPORAL_MASK_RELIABILITY_HIGH="${TEMPORAL_MASK_RELIABILITY_HIGH:-0.04}"
export TEMPORAL_SUPPORT_SMOOTH_KERNEL="${TEMPORAL_SUPPORT_SMOOTH_KERNEL:-5}"
export REMOTE_PARTITION_MODE="${REMOTE_PARTITION_MODE:-uniform}"
export REMOTE_PHASE_COUNT="${REMOTE_PHASE_COUNT:-1}"
export REMOTE_MIN_SAMPLE_POINTS="${REMOTE_MIN_SAMPLE_POINTS:-1}"
