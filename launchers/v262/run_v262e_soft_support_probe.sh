export RUN_TAG="${RUN_TAG:-v262e_soft_support_probe_${STAMP}}"
export WINDOWS="${WINDOWS:-source_target_soft_support}"
export SOURCE_EPOCHS="${SOURCE_EPOCHS:-20}"
export DA_EPOCHS="${DA_EPOCHS:-20}"
export ADAPT_MIN_FACTOR="${ADAPT_MIN_FACTOR:-1.00}"
