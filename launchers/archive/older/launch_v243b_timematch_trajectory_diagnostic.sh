#!/bin/bash

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"

RUN_TAG="${RUN_TAG:-v243b_timematch_trajectory_$(date +%Y%m%d_%H%M%S)}"
LOG_DIR="${LOG_DIR:-$ROOT_DIR/logs/$RUN_TAG}"

export RUN_TAG
export LOG_DIR
export TASKS="${TASKS:-FR2_to_FR1}"
export SEEDS="${SEEDS:-1 2 3 4 5}"
export RAW_WEIGHTS="${RAW_WEIGHTS:-0.75 1.0}"
export GPUS="${GPUS:-0 1 2 3}"
export SOURCE_PRETRAIN_EPOCHS="${SOURCE_PRETRAIN_EPOCHS:-50}"
export TIMEMATCH_EPOCHS="${TIMEMATCH_EPOCHS:-20}"
export TIMEMATCH_STEPS_PER_EPOCH="${TIMEMATCH_STEPS_PER_EPOCH:-500}"
export NUM_WORKERS="${NUM_WORKERS:-16}"

export TIMEMATCH_TRAJECTORY_DIAGNOSTIC="${TIMEMATCH_TRAJECTORY_DIAGNOSTIC:-True}"
export TIMEMATCH_TRAJECTORY_FEATURE_KIND="${TIMEMATCH_TRAJECTORY_FEATURE_KIND:-both}"
export TIMEMATCH_TRAJECTORY_MAX_BATCHES="${TIMEMATCH_TRAJECTORY_MAX_BATCHES:-64}"
export TIMEMATCH_TRAJECTORY_EVERY="${TIMEMATCH_TRAJECTORY_EVERY:-1}"
export TIMEMATCH_TRAJECTORY_NUM_WORKERS="${TIMEMATCH_TRAJECTORY_NUM_WORKERS:-0}"
export TIMEMATCH_TRAJECTORY_SAMPLE_SEED="${TIMEMATCH_TRAJECTORY_SAMPLE_SEED:-1729}"

mkdir -p "$LOG_DIR"

echo "RUN_TAG=$RUN_TAG"
echo "LOG_DIR=$LOG_DIR"
echo "TASKS=$TASKS"
echo "SEEDS=$SEEDS"
echo "RAW_WEIGHTS=$RAW_WEIGHTS"
echo "TIMEMATCH_TRAJECTORY_FEATURE_KIND=$TIMEMATCH_TRAJECTORY_FEATURE_KIND"
echo "TIMEMATCH_TRAJECTORY_MAX_BATCHES=$TIMEMATCH_TRAJECTORY_MAX_BATCHES"
echo "TIMEMATCH_TRAJECTORY_EVERY=$TIMEMATCH_TRAJECTORY_EVERY"
echo "TIMEMATCH_TRAJECTORY_NUM_WORKERS=$TIMEMATCH_TRAJECTORY_NUM_WORKERS"
echo "TIMEMATCH_TRAJECTORY_SAMPLE_SEED=$TIMEMATCH_TRAJECTORY_SAMPLE_SEED"

failed=0
bash "$SCRIPT_DIR/launch_v243b_raw_strength_causal_intervention.sh" || failed=1

python "$ROOT_DIR/analysis/summarize_v243b_timematch_trajectory.py" "$LOG_DIR" || failed=1

echo "Logs saved to: $LOG_DIR"
exit "$failed"
